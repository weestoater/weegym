/**
 * Copies the SCSS files of every Bootswatch theme into src/scss/themes and
 * generates one entry stylesheet per theme in src/themes.
 *
 * Usage: node scripts/sync-bootswatch-themes.js [path-to-bootswatch-package]
 * (defaults to node_modules/bootswatch; get one with `npm pack bootswatch`)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.resolve(
  process.argv[2] || path.join(root, "node_modules/bootswatch"),
);
const distDir = path.join(source, "dist");
const scssDir = path.join(root, "src/scss/themes");
const entryDir = path.join(root, "src/themes");

if (!fs.existsSync(distDir)) {
  console.error(`Bootswatch dist folder not found: ${distDir}`);
  process.exit(1);
}

const themes = fs
  .readdirSync(distDir, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() &&
      fs.existsSync(path.join(distDir, entry.name, "_variables.scss")),
  )
  .map((entry) => entry.name)
  .sort();

fs.mkdirSync(entryDir, { recursive: true });

for (const theme of themes) {
  const target = path.join(scssDir, theme);
  fs.mkdirSync(target, { recursive: true });
  for (const file of ["_variables.scss", "_bootswatch.scss"]) {
    fs.copyFileSync(path.join(distDir, theme, file), path.join(target, file));
  }

  fs.writeFileSync(
    path.join(entryDir, `${theme}.scss`),
    `// Generated by scripts/sync-bootswatch-themes.js\n` +
      `@import "../scss/themes/${theme}/variables";\n` +
      `@import "bootstrap/scss/bootstrap";\n` +
      `@import "../scss/themes/${theme}/bootswatch";\n`,
  );
}

console.log(`Synced ${themes.length} Bootswatch themes: ${themes.join(", ")}`);
